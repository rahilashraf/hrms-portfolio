import { createHmac, timingSafeEqual } from 'node:crypto';
import { constants, createReadStream } from 'node:fs';
import { copyFile, mkdir, readFile, rm, stat } from 'node:fs/promises';
import { dirname, isAbsolute, relative, resolve, sep } from 'node:path';
import type { Readable } from 'node:stream';
import { AwsClient } from 'aws4fetch';
import { attachmentDisposition } from './document-files.js';

/**
 * Batch 9 (D1) — where uploaded document files live. Provider-neutral: a `local` directory for
 * development and tests, or any private S3-compatible bucket (endpoint, region, bucket and keys
 * come from configuration; nothing provider-specific is assumed). PostgreSQL stays the source of
 * truth (DocumentStoredObject); a store only holds bytes under server-generated keys, never
 * overwrites an object, and issues short-lived download URLs after the caller has authorized.
 */

/** A server-generated object key: `documents/<organizationId>/<objectId>` (both UUIDs). */
export const OBJECT_KEY = /^documents\/[0-9a-f-]{36}\/[0-9a-f-]{36}$/;

export function objectKeyFor(organizationId: string, objectId: string) {
  const key = `documents/${organizationId}/${objectId}`;
  if (!OBJECT_KEY.test(key)) throw new Error('Invalid object key components.');
  return key;
}

/** Download URLs live 60 seconds (D4). */
export const VIEW_URL_TTL_SECONDS = 60;

export class ObjectStoreError extends Error {
  constructor(
    readonly code:
      | 'DOCUMENT_STORAGE_UNAVAILABLE'
      | 'DOCUMENT_OBJECT_EXISTS'
      | 'DOCUMENT_OBJECT_KEY_INVALID',
    message: string,
  ) {
    super(message);
    this.name = 'ObjectStoreError';
  }
}

export interface DownloadUrlInput {
  objectId: string;
  key: string;
  fileName: string;
  contentType: string;
  now: Date;
  expiresInSeconds?: number;
}

export abstract class DocumentObjectStore {
  abstract readonly backend: 'local' | 's3';
  /** Writes a verified local file under the key; fails (never overwrites) if the key exists. */
  abstract put(input: {
    key: string;
    filePath: string;
    sizeBytes: number;
    contentType: string;
    sha256: string;
  }): Promise<void>;
  /** The object's size, or null when it does not exist. */
  abstract head(key: string): Promise<{ sizeBytes: number } | null>;
  /** Removes the object; removing a missing object succeeds (idempotent). */
  abstract delete(key: string): Promise<void>;
  /** A short-lived download URL (relative to the API for `local`, absolute for `s3`). */
  abstract downloadUrl(
    input: DownloadUrlInput,
  ): Promise<{ url: string; expiresAt: Date }>;
}

function checkKey(key: string) {
  if (!OBJECT_KEY.test(key))
    throw new ObjectStoreError(
      'DOCUMENT_OBJECT_KEY_INVALID',
      'Object keys are generated by the server.',
    );
}

// ─── Local directory ─────────────────────────────────────────────────────────

/** A local download token: base64url(objectId.expiresAtSeconds).hmac — bound to one object. */
export function signLocalToken(
  signingKey: string,
  objectId: string,
  expiresAt: Date,
) {
  const payload = Buffer.from(
    `${objectId}.${Math.floor(expiresAt.getTime() / 1000)}`,
  ).toString('base64url');
  const mac = createHmac('sha256', signingKey)
    .update(payload)
    .digest('base64url');
  return `${payload}.${mac}`;
}

/** The object id of a valid, unexpired token; null for anything else (tampered, expired…). */
export function verifyLocalToken(signingKey: string, token: string, now: Date) {
  if (typeof token !== 'string' || token.length > 300) return null;
  const [payload, mac, extra] = token.split('.');
  if (!payload || !mac || extra !== undefined) return null;
  const expected = createHmac('sha256', signingKey).update(payload).digest();
  let given: Buffer;
  try {
    given = Buffer.from(mac, 'base64url');
  } catch {
    return null;
  }
  if (given.length !== expected.length || !timingSafeEqual(given, expected))
    return null;
  const [objectId, expires] = Buffer.from(payload, 'base64url')
    .toString('utf8')
    .split('.');
  if (
    !objectId ||
    !/^[0-9a-f-]{36}$/.test(objectId) ||
    !expires ||
    !/^\d+$/.test(expires)
  )
    return null;
  if (Number(expires) * 1000 <= now.getTime()) return null;
  return objectId;
}

export class LocalDocumentObjectStore extends DocumentObjectStore {
  readonly backend = 'local' as const;
  private readonly root: string;

  constructor(
    directory: string,
    private readonly signingKey: string,
  ) {
    super();
    this.root = resolve(directory);
  }

  /** The key's path, proven to stay inside the storage directory (no traversal). */
  pathOf(key: string) {
    checkKey(key);
    const path = resolve(this.root, key);
    const inside = relative(this.root, path);
    if (
      !inside ||
      inside.startsWith('..') ||
      isAbsolute(inside) ||
      inside.split(sep).includes('..')
    )
      throw new ObjectStoreError(
        'DOCUMENT_OBJECT_KEY_INVALID',
        'Object key escapes storage.',
      );
    return path;
  }

  async put(input: { key: string; filePath: string }) {
    const path = this.pathOf(input.key);
    await mkdir(dirname(path), { recursive: true, mode: 0o700 });
    try {
      // COPYFILE_EXCL: never overwrite an existing object.
      await copyFile(input.filePath, path, constants.COPYFILE_EXCL);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'EEXIST')
        throw new ObjectStoreError(
          'DOCUMENT_OBJECT_EXISTS',
          'The object already exists.',
        );
      throw new ObjectStoreError(
        'DOCUMENT_STORAGE_UNAVAILABLE',
        'The file could not be stored.',
      );
    }
  }

  async head(key: string) {
    try {
      const info = await stat(this.pathOf(key));
      return { sizeBytes: info.size };
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw new ObjectStoreError(
        'DOCUMENT_STORAGE_UNAVAILABLE',
        'Storage is unavailable.',
      );
    }
  }

  async delete(key: string) {
    await rm(this.pathOf(key), { force: true });
  }

  async downloadUrl(input: DownloadUrlInput) {
    checkKey(input.key);
    const expiresAt = new Date(
      input.now.getTime() +
        (input.expiresInSeconds ?? VIEW_URL_TTL_SECONDS) * 1000,
    );
    return {
      url: `/documents/files/${signLocalToken(this.signingKey, input.objectId, expiresAt)}`,
      expiresAt,
    };
  }

  verifyToken(token: string, now: Date) {
    return verifyLocalToken(this.signingKey, token, now);
  }

  openRead(key: string): Readable {
    return createReadStream(this.pathOf(key));
  }
}

// ─── S3-compatible ───────────────────────────────────────────────────────────

export interface S3Settings {
  endpoint: string;
  region: string;
  bucket: string;
  accessKeyId: string;
  secretAccessKey: string;
  forcePathStyle: boolean;
}

/**
 * Any S3-compatible service through signed requests (SigV4): PUT with the payload's SHA-256
 * (the service verifies it) and `If-None-Match: *` (no overwrite), HEAD, DELETE, and presigned
 * GET URLs that force a download with the stored type. The bucket must be private.
 */
export class S3DocumentObjectStore extends DocumentObjectStore {
  readonly backend = 's3' as const;
  private readonly client: AwsClient;

  constructor(
    private readonly settings: S3Settings,
    private readonly fetcher: typeof fetch = fetch,
  ) {
    super();
    this.client = new AwsClient({
      accessKeyId: settings.accessKeyId,
      secretAccessKey: settings.secretAccessKey,
      region: settings.region,
      service: 's3',
    });
  }

  objectUrl(key: string) {
    checkKey(key);
    const endpoint = new URL(this.settings.endpoint);
    const path = key.split('/').map(encodeURIComponent).join('/');
    if (this.settings.forcePathStyle) {
      endpoint.pathname = `${endpoint.pathname.replace(/\/+$/, '')}/${this.settings.bucket}/${path}`;
    } else {
      endpoint.hostname = `${this.settings.bucket}.${endpoint.hostname}`;
      endpoint.pathname = `${endpoint.pathname.replace(/\/+$/, '')}/${path}`;
    }
    return endpoint.toString();
  }

  private async send(request: Request) {
    const signed = await this.client.sign(request);
    try {
      return await this.fetcher(signed);
    } catch {
      throw new ObjectStoreError(
        'DOCUMENT_STORAGE_UNAVAILABLE',
        'Storage is unavailable.',
      );
    }
  }

  async put(input: {
    key: string;
    filePath: string;
    sizeBytes: number;
    contentType: string;
    sha256: string;
  }) {
    const body = await readFile(input.filePath);
    const response = await this.send(
      new Request(this.objectUrl(input.key), {
        method: 'PUT',
        body,
        headers: {
          'Content-Type': input.contentType,
          'Content-Length': String(input.sizeBytes),
          'X-Amz-Content-Sha256': input.sha256,
          'If-None-Match': '*',
        },
      }),
    );
    if (response.status === 412)
      throw new ObjectStoreError(
        'DOCUMENT_OBJECT_EXISTS',
        'The object already exists.',
      );
    if (!response.ok)
      throw new ObjectStoreError(
        'DOCUMENT_STORAGE_UNAVAILABLE',
        'The file could not be stored.',
      );
  }

  async head(key: string) {
    const response = await this.send(
      new Request(this.objectUrl(key), { method: 'HEAD' }),
    );
    if (response.status === 404) return null;
    if (!response.ok)
      throw new ObjectStoreError(
        'DOCUMENT_STORAGE_UNAVAILABLE',
        'Storage is unavailable.',
      );
    return { sizeBytes: Number(response.headers.get('content-length') ?? 0) };
  }

  async delete(key: string) {
    const response = await this.send(
      new Request(this.objectUrl(key), { method: 'DELETE' }),
    );
    if (!response.ok && response.status !== 404)
      throw new ObjectStoreError(
        'DOCUMENT_STORAGE_UNAVAILABLE',
        'Storage is unavailable.',
      );
  }

  async downloadUrl(input: DownloadUrlInput) {
    const seconds = input.expiresInSeconds ?? VIEW_URL_TTL_SECONDS;
    const url = new URL(this.objectUrl(input.key));
    url.searchParams.set('X-Amz-Expires', String(seconds));
    url.searchParams.set(
      'response-content-disposition',
      attachmentDisposition(input.fileName),
    );
    url.searchParams.set('response-content-type', input.contentType);
    url.searchParams.set('response-cache-control', 'no-store');
    const signed = await this.client.sign(
      new Request(url.toString(), { method: 'GET' }),
      {
        aws: { signQuery: true, datetime: amzDate(input.now) },
      },
    );
    return {
      url: signed.url,
      expiresAt: new Date(input.now.getTime() + seconds * 1000),
    };
  }
}

function amzDate(date: Date) {
  return date.toISOString().replace(/[:-]|\.\d{3}/g, '');
}

// ─── Configuration ───────────────────────────────────────────────────────────

export interface DocumentStorageSettings {
  store: DocumentObjectStore | null;
  maxUploadBytes: number;
  requireMalwareScan: boolean;
}

/**
 * The document storage of an environment (validated again by @hrms/config at API startup):
 * none (uploads refused with DOCUMENT_STORAGE_NOT_CONFIGURED), local, or s3.
 */
export function documentStorageFromEnv(
  env: Record<string, string | undefined> = process.env,
): DocumentStorageSettings {
  const driver = (env.DOCUMENT_STORAGE_DRIVER ?? 'none').trim() || 'none';
  // An empty value (as in .env.example) means the default, never a 0- or 1-byte limit.
  const configured = Number(env.DOCUMENT_UPLOAD_MAX_BYTES?.trim() || NaN);
  const maxUploadBytes =
    Number.isInteger(configured) && configured >= 1
      ? Math.min(configured, 25 * 1024 * 1024)
      : 10 * 1024 * 1024;
  const requireMalwareScan = env.DOCUMENT_REQUIRE_MALWARE_SCAN === 'true';
  if (driver === 'none')
    return { store: null, maxUploadBytes, requireMalwareScan };
  if (driver === 'local') {
    if (
      env.NODE_ENV === 'production' &&
      env.DOCUMENT_STORAGE_ALLOW_LOCAL_IN_PRODUCTION !== 'true'
    )
      throw new Error('Local document storage is refused in production.');
    const directory = env.DOCUMENT_STORAGE_LOCAL_DIR;
    const signingKey = env.DOCUMENT_URL_SIGNING_KEY;
    if (!directory || !signingKey || Buffer.byteLength(signingKey) < 32)
      throw new Error(
        'DOCUMENT_STORAGE_LOCAL_DIR and DOCUMENT_URL_SIGNING_KEY (32+ bytes) are required for local document storage.',
      );
    return {
      store: new LocalDocumentObjectStore(directory, signingKey),
      maxUploadBytes,
      requireMalwareScan,
    };
  }
  if (driver === 's3') {
    const required = [
      'DOCUMENT_S3_ENDPOINT',
      'DOCUMENT_S3_REGION',
      'DOCUMENT_S3_BUCKET',
      'DOCUMENT_S3_ACCESS_KEY_ID',
      'DOCUMENT_S3_SECRET_ACCESS_KEY',
    ] as const;
    const missing = required.filter((key) => !env[key]);
    if (missing.length > 0)
      throw new Error(
        `${missing.join(', ')} required for s3 document storage.`,
      );
    if (
      env.NODE_ENV === 'production' &&
      new URL(env.DOCUMENT_S3_ENDPOINT!).protocol !== 'https:'
    )
      throw new Error('DOCUMENT_S3_ENDPOINT must use https in production.');
    return {
      store: new S3DocumentObjectStore({
        endpoint: env.DOCUMENT_S3_ENDPOINT!,
        region: env.DOCUMENT_S3_REGION!,
        bucket: env.DOCUMENT_S3_BUCKET!,
        accessKeyId: env.DOCUMENT_S3_ACCESS_KEY_ID!,
        secretAccessKey: env.DOCUMENT_S3_SECRET_ACCESS_KEY!,
        forcePathStyle: env.DOCUMENT_S3_FORCE_PATH_STYLE === 'true',
      }),
      maxUploadBytes,
      requireMalwareScan,
    };
  }
  throw new Error(`Unknown DOCUMENT_STORAGE_DRIVER: ${driver}.`);
}
