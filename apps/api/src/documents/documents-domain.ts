/**
 * Phase 15 — pure Documents & Employee Records rules (no Nest services, no database). Each
 * rule mirrors, and fails before, the matching constraint or trigger of the phase15 migration.
 */

const CODE = /^[A-Z0-9_-]{2,64}$/;
export const EXPIRING_SOON_DAYS = 30;

export function invalid(
  code: string,
  message: string,
  extra: Record<string, unknown> = {},
): never {
  throw new BadRequestException(domainError(400, code, message, extra));
}

export function parseDocumentCode(value: unknown): string {
  const code = typeof value === 'string' ? value.trim().toUpperCase() : '';
  if (!CODE.test(code)) {
    invalid(
      'DOCUMENT_CODE_INVALID',
      'code must be 2–64 characters: letters, digits, "_" or "-" (e.g. "FIRST-AID").',
    );
  }
  return code;
}

export function parseText(
  value: unknown,
  field: string,
  options: { required?: boolean; max?: number } = {},
): string | null {
  const text = typeof value === 'string' ? value.trim() : '';
  if (!text) {
    if (options.required)
      invalid('DOCUMENT_TEXT_REQUIRED', `${field} is required.`);
    return null;
  }
  if (text.length > (options.max ?? 10_000))
    invalid('DOCUMENT_TEXT_TOO_LONG', `${field} is too long.`);
  return text;
}

// ─── Confidentiality ─────────────────────────────────────────────────────────

const RANK: Record<DocumentConfidentiality, number> = {
  EMPLOYEE_VISIBLE: 0,
  MANAGER_VISIBLE: 1,
  HR_ONLY: 2,
  RESTRICTED: 3,
};

export type DocumentReadPermission =
  'document.read' | 'document.confidential.read' | 'document.restricted.read';

/** The read permission a confidentiality level needs (each covers the levels below it). */
export function readPermissionFor(
  level: DocumentConfidentiality,
): DocumentReadPermission {
  if (level === 'RESTRICTED') return 'document.restricted.read';
  if (level === 'HR_ONLY') return 'document.confidential.read';
  return 'document.read';
}

/** The highest level a set of read permissions reaches (-1: none). */
export function clearanceOf(permissions: ReadonlySet<string>): number {
  if (permissions.has('document.restricted.read')) return RANK.RESTRICTED;
  if (permissions.has('document.confidential.read')) return RANK.HR_ONLY;
  if (permissions.has('document.read')) return RANK.MANAGER_VISIBLE;
  return -1;
}

export function levelWithin(level: DocumentConfidentiality, clearance: number) {
  return RANK[level] <= clearance;
}

// ─── Storage references (provider-neutral) ───────────────────────────────────

export interface StorageReferenceInput {
  provider: DocumentStorageProvider;
  externalUrl?: string | null;
  /**
   * Batch 9 (F2): never accepted from a client — internal object keys are generated by the
   * server and bound to a stored object (see document-upload.service.ts). Kept in the input
   * shape only to refuse it with a clear error.
   */
  storageKey?: string | null;
  /** Batch 9: an uploaded file (INTERNAL_OBJECT_STORAGE), attached by the server. */
  uploadId?: string | null;
  externalFileId?: string | null;
  fileName?: string | null;
  mimeType?: string | null;
  sizeBytes?: number | null;
}

/**
 * A storage reference: metadata and an https link, a Drive file id or an object-storage key —
 * never file contents. Google Drive references are only validated in shape; no Google API is
 * called (a later Google Workspace adapter resolves and monitors them).
 */
export function parseStorageReference(input: StorageReferenceInput) {
  const externalUrl = parseText(input.externalUrl, 'externalUrl', {
    max: 2000,
  });
  if (externalUrl && !/^https:\/\/\S+$/i.test(externalUrl))
    invalid('DOCUMENT_URL_INVALID', 'Links must be https URLs.');
  const externalFileId = parseText(input.externalFileId, 'externalFileId', {
    max: 500,
  });
  if (externalFileId && !/^[\w.:/-]+$/.test(externalFileId))
    invalid(
      'DOCUMENT_FILE_ID_INVALID',
      'externalFileId has invalid characters.',
    );
  // Batch 9 (F2): a client never chooses where a file is stored.
  if (
    input.storageKey !== undefined &&
    input.storageKey !== null &&
    String(input.storageKey).trim() !== ''
  ) {
    invalid(
      'DOCUMENT_STORAGE_KEY_NOT_ACCEPTED',
      'Storage keys are assigned by the server; upload the file instead.',
    );
  }
  const uploadId =
    typeof input.uploadId === 'string' && input.uploadId.trim()
      ? input.uploadId.trim()
      : null;
  if (
    uploadId &&
    !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
      uploadId,
    )
  )
    invalid('DOCUMENT_UPLOAD_INVALID', 'uploadId is not an upload id.');
  switch (input.provider) {
    case 'EXTERNAL_URL':
      if (!externalUrl)
        invalid(
          'DOCUMENT_REFERENCE_REQUIRED',
          'An external document needs its https link.',
        );
      break;
    case 'GOOGLE_DRIVE':
      if (!externalUrl && !externalFileId)
        invalid(
          'DOCUMENT_REFERENCE_REQUIRED',
          'A Google Drive document needs its link or file id.',
        );
      break;
    case 'INTERNAL_OBJECT_STORAGE':
      if (!uploadId)
        invalid(
          'DOCUMENT_UPLOAD_REQUIRED',
          'A stored document needs an uploaded file (uploadId).',
        );
      break;
    case 'MANUAL_REFERENCE':
      break;
  }
  if (input.provider !== 'INTERNAL_OBJECT_STORAGE' && uploadId) {
    invalid(
      'DOCUMENT_UPLOAD_INVALID',
      'Only internal object storage takes an uploaded file.',
    );
  }
  const mimeType = parseText(input.mimeType, 'mimeType', { max: 200 });
  if (mimeType && !/^[\w.+-]+\/[\w.+-]+$/.test(mimeType))
    invalid('DOCUMENT_MIME_INVALID', 'mimeType is not a media type.');
  const sizeBytes = input.sizeBytes ?? null;
  if (sizeBytes !== null && (!Number.isInteger(sizeBytes) || sizeBytes < 0))
    invalid('DOCUMENT_SIZE_INVALID', 'sizeBytes is a whole number.');
  return {
    provider: input.provider,
    externalUrl,
    externalFileId,
    fileName: parseText(input.fileName, 'fileName', { max: 300 }),
    mimeType,
    sizeBytes,
    /** Attached by the server (never written from client input). */
    uploadId,
  };
}

// ─── Expiry ──────────────────────────────────────────────────────────────────

export type ExpiryStatus = 'NO_EXPIRY' | 'VALID' | 'EXPIRING_SOON' | 'EXPIRED';

/** Date-derived expiry status (no job needed): expired after the expiry day. */
export function expiryStatus(
  expiresOn: Date | null,
  today: Date,
): ExpiryStatus {
  if (!expiresOn) return 'NO_EXPIRY';
  if (expiresOn < today) return 'EXPIRED';
  if (expiresOn <= addDays(today, EXPIRING_SOON_DAYS)) return 'EXPIRING_SOON';
  return 'VALID';
}

/** A document satisfies a requirement while active and not expired. */
export function satisfies(
  document: { status: string; expiresOn: Date | null },
  today: Date,
) {
  return (
    document.status === 'ACTIVE' &&
    expiryStatus(document.expiresOn, today) !== 'EXPIRED'
  );
}

// ─── Requirements ────────────────────────────────────────────────────────────

export interface RequirementCriteria {
  employmentType: string | null;
  departmentId: string | null;
  positionId: string | null;
}

/** A requirement applies to an assignment matching every criterion it sets. */
export function requirementApplies(
  requirement: RequirementCriteria,
  assignment: {
    employmentType: string;
    positionId: string;
    departmentId: string | null;
  },
) {
  return (
    (!requirement.employmentType ||
      requirement.employmentType === assignment.employmentType) &&
    (!requirement.departmentId ||
      requirement.departmentId === assignment.departmentId) &&
    (!requirement.positionId ||
      requirement.positionId === assignment.positionId)
  );
}

